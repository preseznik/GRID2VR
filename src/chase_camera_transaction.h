struct TransactionIdentity {
    uintptr_t camera{},manager{},provider{},entity{};
    uint32_t thread{};
    uint64_t evaluation{},suspension{};
    ReplayClockSample replay;
    uint32_t replayMode{},replayDirector{};
    bool operator==(const TransactionIdentity&) const=default;
};

// Validates an observed native call sequence, not the authenticity/readability of
// arbitrary addresses. Callers must capture _ReturnAddress/_AddressOfReturnAddress
// in the actual native wrappers, hold their lock, check supported-image guards,
// and independently recheck ownership before and after each forwarded call.
class CameraTransaction {
public:
    bool Begin(const TransactionIdentity& identity,uintptr_t callerRva,
               uintptr_t returnSlot,uintptr_t timing) {
        if(state_!=State::Idle || callerRva!=transactionBeginCallerRva ||
           !Valid(identity) || !Stack(returnSlot) || timing!=returnSlot+transactionTimingOffset ||
           (seen_ && identity==last_))return Fail();
        identity_=last_=identity;
        seen_=true;
        returnSlot_=returnSlot;
        state_=State::Started;
        return true;
    }
    bool Copy(const TransactionIdentity& identity,uintptr_t callerRva,
              uintptr_t returnSlot,uintptr_t record) {
        if(state_!=State::Started || callerRva!=transactionCopyCallerRva ||
           !Same(identity,returnSlot,record))return Fail();
        state_=State::Copied;
        return true;
    }
    // Call after the original slot 25 returns; success permits recapturing its
    // final displayed pose. The helper itself never copies or alters a pose.
    bool Commit(const TransactionIdentity& identity,uintptr_t callerRva,
                uintptr_t returnSlot,uintptr_t record) {
        if(state_!=State::Copied || callerRva!=transactionCommitCallerRva ||
           !Same(identity,returnSlot,record))return Fail();
        ClearActive();
        return true;
    }
    bool Active()const {return state_!=State::Idle;}
    const TransactionIdentity& Identity()const {return identity_;}
    uintptr_t Record()const {return Active()?returnSlot_+transactionRecordOffset:0;}
    // Explicit session/camera invalidation; an unexpected call instead retains
    // the accepted evaluation identity so it cannot restart a half transaction.
    void Reset() {*this={};}

private:
    enum class State {Idle,Started,Copied};
    State state_{State::Idle};
    TransactionIdentity identity_{},last_{};
    uintptr_t returnSlot_{};
    bool seen_{};
    static bool Pointer(uintptr_t value) {
        return value>=0x10000 && value<=UINT32_MAX-0x10000 && value%4==0;
    }
    static bool Valid(const TransactionIdentity& value) {
        return Pointer(value.camera) && Pointer(value.manager) &&
               Pointer(value.provider) && Pointer(value.entity) && value.thread!=0;
    }
    static bool Stack(uintptr_t value) {
        // 70ec10 aligns EBP to 16, allocates 0x298 and saves ESI/EDI. Each
        // qualified call pushes one argument then its return address:
        // S=EBP-0x2a8; record=EBP-0x290; timing=EBP-0x14 (16 bytes).
        return value>=0x10000 && value<=UINT32_MAX-0x10000-0x2a4 && value%16==8;
    }
    bool Same(const TransactionIdentity& identity,uintptr_t slot,uintptr_t record)const {
        return identity==identity_ && slot==returnSlot_ && record==slot+transactionRecordOffset;
    }
    void ClearActive() {state_=State::Idle;identity_={};returnSlot_=0;}
    bool Fail() {ClearActive();return false;}
};

