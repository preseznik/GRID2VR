inline bool GuardsMatch(uintptr_t base) {
    if(!base || base>UINT32_MAX-providerTableRva-0x20 ||
       !MatchesInstructions(reinterpret_cast<void*>(base+routines[0]),updateEntry) ||
       !MatchesInstructions(reinterpret_cast<void*>(base+routines[0]+0x2d),updateCall) ||
       !MatchesInstructions(reinterpret_cast<void*>(base+routines[1]),alternateBody) ||
       !MatchesInstructions(reinterpret_cast<void*>(base+routines[2]),copyBody) ||
       !MatchesInstructions(reinterpret_cast<void*>(base+routines[3]),obstructionBody) ||
       !MatchesInstructions(reinterpret_cast<void*>(base+routines[4]),recordPointerBody) ||
       !MatchesInstructions(reinterpret_cast<void*>(base+0x804780),viewConverterCall) ||
       !MatchesInstructions(reinterpret_cast<void*>(base+0x118581),selectedViewA) ||
       !MatchesInstructions(reinterpret_cast<void*>(base+0x21a5f3),selectedViewB) ||
       !MatchesInstructions(reinterpret_cast<void*>(base+0x2e3930),auxiliaryFrameEntry) ||
       !MatchesInstructions(reinterpret_cast<void*>(base+0x2e394b),auxiliaryFrameAllocation) ||
       !MatchesInstructions(reinterpret_cast<void*>(base+0x2e3c16),auxiliaryViewCall) ||
       !MatchesInstructions(reinterpret_cast<void*>(base+routines[5]),mainSceneEntry) ||
       !MatchesInstructions(reinterpret_cast<void*>(base+0x3be050),completeSceneEntry) ||
       !MatchesInstructions(reinterpret_cast<void*>(base+0x3be087),mainSceneCall) ||
       !MatchesInstructions(reinterpret_cast<void*>(base+0x7a7cb3),completeSceneCall) ||
       !MatchesInstructions(reinterpret_cast<void*>(base+routines[6]),ProviderPositionGuard(base)) ||
       // Keep each guarded read within MatchesInstructions' 64-byte bound.
       !MatchesInstructions(reinterpret_cast<void*>(base+0x1f78a0),std::span<const uint8_t>(preQueryEntry).first(48)) ||
       !MatchesInstructions(reinterpret_cast<void*>(base+0x1f78a0+48),std::span<const uint8_t>(preQueryEntry).subspan(48)) ||
       !MatchesInstructions(reinterpret_cast<void*>(base+0x61eb91),preQueryStage) ||
       !MatchesInstructions(reinterpret_cast<void*>(base+providerBasisRva),providerBasisBody))return false;
    for(size_t i=0;i<slots.size();++i) {
        uintptr_t actual{};
        if(!ReadMemory(reinterpret_cast<void*>(base+SlotRva(i)),&actual,sizeof(actual)) || actual!=base+routines[i])return false;
    }
    uint32_t basis{};
    if(!ReadMemory(reinterpret_cast<void*>(base+providerBasisSlotRva),&basis,sizeof(basis)) || basis!=base+providerBasisRva)return false;
    return true;
}
