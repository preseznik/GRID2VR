// 32-bit absolute operands; after relocation each holds base+target.
struct AddressGuard {uintptr_t rva,target;};
inline constexpr AddressGuard addressGuards[]{
    {0x5b795b,modeIndexRva},{0x718791,monitorVtableRva},{0x212f24,monitorIndexRva},{0x212f75,resetCallbackRva},
    {0x212f81,dispatcherIndexRva},{0x663e7f,modeIndexRva},{0x663ec2,blockFlagRva},{0x2a662e,benchmarkSettingsRva},
};
inline bool InstructionsMatch(uintptr_t base) {
    if(!base) return false;
    for(const auto& guard:codeGuards) {
        if(!MatchesInstructions(reinterpret_cast<void*>(base+guard.rva),std::span<const uint8_t>(guard.bytes.data(),guard.length))) return false;
    }
    for(const auto& guard:addressGuards) {
        uint32_t value{};
        if(!ReadMemory(reinterpret_cast<void*>(base+guard.rva),&value,sizeof(value)) || value!=static_cast<uint32_t>(base+guard.target)) return false;
    }
    return true;
}
