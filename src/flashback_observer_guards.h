// The game hashes its own code in thousands of ranges and faults on any inline
// patch (the first observer build crashed at frame 3), so nothing is hooked.
// The code guards below pin the instructions that establish each field read
// and the one data word written (the benchmark mode, see BenchmarkFlagPolicy).
//
// Player car -> [[car+0x2c]+4][monitorIndex] is the FlashbackMonitor (attach 0x212f1a).
