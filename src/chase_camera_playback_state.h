inline bool ReplayStateAddress(uintptr_t value) {
    return value>=0x10000 && value<=UINT32_MAX-0x10000 && value%4==0;
}
inline bool ReplayStateImage(uintptr_t base) {
    return ReplayStateAddress(base) && base<=UINT32_MAX-0xdef810-4;
}
// Read is bool(uintptr_t,void*,size_t). Requires the supported executable
// fingerprint separately. This verifies bytes only; it never invokes game code.
template<class Read> bool ReplayStateGuardsMatch(uintptr_t base,Read&& read) {
    if(!ReplayStateImage(base))return false;
    for(const auto& guard:ReplayStateGuards(base)) {
        std::array<uint8_t,48> actual{};
        if(!read(base+guard.rva,actual.data(),guard.size))return false;
        for(size_t i=0;i<guard.size;++i)if(actual[i]!=guard.bytes[i])return false;
    }
    return true;
}
// Two bounded reads reject visible ownership/state changes, not ABA or races.
// Retain the independent local-car, selected-camera, focus and world-pause gates.
// Call only after ReplayStateGuardsMatch and executable fingerprint validation.
template<class Read> const char* NativeDrivingReplayRefusal(uintptr_t base,Read&& read) {
    if(!ReplayStateImage(base))return "driving_replay_image_invalid";
    using Snapshot=std::array<uint32_t,7>; // root, state, UI, UI table, mode, override, transport
    const auto capture=[&](Snapshot& value)->const char* {
        if(!read(base+0xdef810,&value[0],4))return "driving_replay_root_unreadable";
        if(!ReplayStateAddress(value[0]))return "driving_replay_root_invalid";
        if(!read(value[0]+0x10,&value[1],4))return "driving_replay_state_unreadable";
        if(!ReplayStateAddress(value[1]))return "driving_replay_state_invalid";
        if(!read(value[1]+0x148c,&value[2],4))return "driving_replay_ui_unreadable";
        if(!ReplayStateAddress(value[2]))return "driving_replay_ui_invalid";
        if(!read(value[2],&value[3],4))return "driving_replay_type_unreadable";
        if(value[3]!=base+0xd10640)return "driving_replay_type_mismatch";
        if(!read(value[2]+0x1d8,&value[4],4))return "driving_replay_mode_unreadable";
        if(value[4]!=0 && value[4]!=7)return "driving_replay_active_or_unknown";
        if(!read(value[2]+0x7640,&value[5],4))return "driving_replay_override_unreadable";
        if(value[5]!=0)return "driving_replay_override_active_or_unknown";
        if(!read(value[2]+0x7604,&value[6],4))return "driving_replay_transport_unreadable";
        if(value[6]!=0 && value[6]!=2)return "driving_replay_transport_active_or_unknown";
        return nullptr;
    };
    Snapshot first{},second{};
    if(const auto failure=capture(first))return failure;
    if(capture(second) || first!=second)return "driving_replay_graph_changed";
    return nullptr;
}
