"""Build the optional pack and compile-time atlas identities from local exports.

Original DDS files stay local. Only generated replacement DDS files enter the ZIP.
Use --draft only to compile/test an incomplete catalog during artwork production.
"""
import argparse
import hashlib
import json
import re
import struct
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
VERSION = '0.2.0-preview.2'
def sha(data): return hashlib.sha256(data).hexdigest()
def layout(data, size, mips, length):
    if len(data) != length or data[:4] != b'DDS ' or struct.unpack_from('<I', data, 4)[0] != 124 or struct.unpack_from('<2I', data, 12) != (size, size) or struct.unpack_from('<I', data, 28)[0] != mips or data[84:88] != b'DXT1':
        raise ValueError('Unexpected BC1 DDS layout')

def build(lab, draft=False, keep_stock=()):
    inventory = json.loads((lab/'originals-all/inventory.json').read_text(encoding='utf-8-sig'))['cars']
    keep_stock = set(keep_stock)
    if not keep_stock.issubset({r['car'] for r in inventory}): raise ValueError('Unknown stock-only car')
    groups = {}
    for row in sorted(inventory, key=lambda r: (r['dlc'], r['car'])):
        car = row['car']
        if not re.fullmatch('[a-z0-9]{3}', car): raise ValueError('Invalid car ID')
        data = (lab/f'originals-all/{car}.dds').read_bytes()
        if sha(data) != row['ddsSha256']: raise ValueError('Changed source export')
        layout(data, 512, 10, 174904)
        group = groups.setdefault(sha(data[128:]), {'car': car, 'cars': [], 'source10': sha(data[128:]), 'source8': sha(data[128:-16])})
        group['cars'].append(car)
    rows, missing = [], []
    for group in sorted(groups.values(), key=lambda r: r['car']):
        if keep_stock.intersection(group['cars']):
            if not set(group['cars']).issubset(keep_stock): raise ValueError('Shared atlas cannot be partially excluded')
            continue
        path = lab/'dds'/(group['car']+'.dds')
        if not path.is_file():
            missing += group['cars']; continue
        data = path.read_bytes(); layout(data, 2048, 12, 2796344)
        rows.append(dict(group, file=path.name, sha256=sha(data), bytes=len(data)))
    if missing and not draft: raise ValueError('Missing replacement artwork: ' + ', '.join(missing))
    if not rows: raise ValueError('No replacements')
    header = '// Generated by tools/build_cockpit_texture_pack.py; exact uploaded BC1 mip identities.\n'
    header += ''.join('{' + ','.join(json.dumps(row[key]) for key in ('car','source10','source8','sha256')) + '},\n' for row in rows)
    (ROOT/'src/cockpit_texture_catalog.inc').write_text(header, encoding='ascii')
    status = dict(schema=1, version=VERSION, cars=sum(len(r['cars']) for r in rows), uniqueAtlases=len(rows), stockCars=sorted(keep_stock), missingCars=missing, complete=not missing, draft=draft)
    (lab/'coverage.json').write_text(json.dumps(status, indent=2)+'\n')
    if draft: return status
    payload = {r['file']: (lab/'dds'/r['file']).read_bytes() for r in rows}
    payload['pack.json'] = (json.dumps(dict(schema=1, id='cockpit-textures', version=VERSION, carCount=len(inventory), replacementCarCount=status['cars'], stockCars=status['stockCars'], atlases=rows, generatedSize=1254, installedSize=2048, mips=12, format='BC1', gameFilesModified=False), indent=2)+'\n').encode()
    stock_note = 'Kept original in this preview: '+', '.join(sorted(keep_stock))+'.\n' if keep_stock else ''
    payload['README.txt'] = (f'GRID2VR cockpit textures {VERSION}\n\nOptional artwork for {status["cars"]} cars ({len(rows)} unique atlases).\n{stock_note}Install with tools/Cockpit-TexturePack.ps1 -Action Install -GameRoot <game> -ZipPath <ZIP>.\nSelect New cockpit textures in the launcher and launch again.\nOld cockpit textures keeps the original artwork. Missing/changed textures use originals.\nPack lives under GRID2VR/addons/cockpit-textures/{VERSION}.\nGame archives and saves are not modified.\n\nAI-generated artwork, based on the stock UV layout. Native output 1254 square,\nresized to 2048 square BC1 with 12 mips. Markings/materials may differ.\nThis preview has offline validation; per-car headset acceptance remains pending.\n').encode()
    archive = lab/f'GRID2VR-CockpitTextures-{VERSION}.zip'
    with zipfile.ZipFile(archive, 'x', compression=zipfile.ZIP_DEFLATED, compresslevel=6) as z:
        for name, data in sorted(payload.items()): z.writestr(f'cockpit-textures/{VERSION}/{name}', data)
    catalog = dict(schema=1, version=VERSION, zipSha256=sha(archive.read_bytes()), zipBytes=archive.stat().st_size, files={name:sha(data) for name,data in sorted(payload.items())})
    catalogPath = ROOT/'tools/data/cockpit-texture-pack.json'
    catalogPath.write_text(json.dumps(catalog,indent=2)+'\n')
    installer = ROOT/'tools/Cockpit-TexturePack.ps1'
    text = installer.read_text()
    text, count = re.subn(r"\$catalogHash='[a-zA-Z0-9_-]+'", "$catalogHash='"+sha(catalogPath.read_bytes())+"'", text)
    if count != 1: raise ValueError('Installer catalog pin missing')
    installer.write_text(text)
    return dict(status, archive=str(archive), zipBytes=catalog['zipBytes'], zipSha256=catalog['zipSha256'])

