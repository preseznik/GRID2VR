"""Generate the exact stock sponsor board mip0 identity catalog.

Read-only on the installed game. The opt-in draw bias targets board.tga, not
cloth.tga. Hash compressed BC1 mip0 bytes without changing textures or geometry.
"""
import argparse
import hashlib
import struct
from pathlib import Path

WIDTH, HEIGHT, BLOCK = 1024, 256, 8
MIP0 = (WIDTH // 4) * (HEIGHT // 4) * BLOCK
MAX_FILE = 16 * 1024 * 1024


def u32(data, offset):
    return struct.unpack_from('>I', data, offset)[0]


def textures(data):
    """Yield (attributes, raw block) for every TEXTURE node of a PSSG file."""
    if data[:4] != b'PSSG':
        raise ValueError('not a PSSG file')
    attribute_count, node_count = u32(data, 8), u32(data, 12)
    offset, nodes, attributes = 16, {}, {}
    for _ in range(node_count):
        node_id, length = u32(data, offset), u32(data, offset + 4)
        offset += 8
        nodes[node_id] = data[offset:offset + length].decode('ascii')
        offset += length
        count = u32(data, offset)
        offset += 4
        for _ in range(count):
            attribute_id, length = u32(data, offset), u32(data, offset + 4)
            offset += 8
            attributes[attribute_id] = data[offset:offset + length].decode('ascii')
            offset += length
    if len(attributes) > attribute_count + 1024:
        raise ValueError('unexpected schema')

    def is_node(at, end):
        return end - at >= 12 and u32(data, at) in nodes and at + 8 + u32(data, at + 4) <= end

    def walk(at, end, depth=0):
        # In document order: a TEXTURE is followed by its own image block before any sibling.
        if depth > 64:
            raise ValueError('nesting too deep')
        while at < end and is_node(at, end):
            node_end = at + 8 + u32(data, at + 4)
            name = nodes[u32(data, at)]
            attribute_end = at + 12 + u32(data, at + 8)
            values, cursor = {}, at + 12
            while cursor < attribute_end:
                attribute_id, length = u32(data, cursor), u32(data, cursor + 4)
                values[attributes.get(attribute_id)] = data[cursor + 8:cursor + 8 + length]
                cursor += 8 + length
            if name == 'TEXTUREIMAGEBLOCKDATA':
                yield None, (attribute_end, node_end)
            elif name == 'TEXTURE':
                yield values, None
            if is_node(attribute_end, node_end):
                yield from walk(attribute_end, node_end, depth + 1)
            at = node_end

    yield from walk(offset, len(data))


def text(value):
    return value[4:4 + u32(value, 0)].decode('ascii')


def board_hashes(sponsors):
    hashes = set()
    files = sorted(sponsors.glob('*.pssg'))
    if not files:
        raise ValueError(f'no sponsor files in {sponsors}')
    for path in files:
        if path.stat().st_size > MAX_FILE:
            raise ValueError(f'unexpected size: {path.name}')
        data = path.read_bytes()
        pending = None
        for values, block in textures(data):
            if values is not None:
                pending = values
                continue
            if pending is None or text(pending['id']) != 'board.tga':
                continue
            if (u32(pending['width'], 0), u32(pending['height'], 0), text(pending['texelFormat'])) != (WIDTH, HEIGHT, 'dxt1'):
                raise ValueError(f'unexpected board layout in {path.name}')
            start, end = block
            if end - start < MIP0:
                raise ValueError(f'short board block in {path.name}')
            hashes.add(hashlib.sha256(data[start:start + MIP0]).hexdigest())
            pending = None
    return sorted(hashes)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--game-root', type=Path, required=True)
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    hashes = board_hashes(args.game_root / 'tracks' / 'sponsors')
    lines = ['// Generated by tools/sponsor_board_catalog.py from tracks/sponsors/*.pssg (board.tga, mip 0, 1024x256 BC1).']
    lines += [f'"{h}",' for h in hashes]
    args.output.write_text('\n'.join(lines) + '\n', encoding='ascii', newline='\n')
    print(f'{len(hashes)} board identities -> {args.output}')


if __name__ == '__main__':
    main()
